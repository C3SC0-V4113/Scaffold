import { agentStateDirs, testReportDirs, usesCloudflareAdapter } from './ignores.js';

interface EslintConfigOptions
  extends Pick<CreateOptions, 'framework' | 'unit' | 'e2e'>,
    Partial<Pick<CreateOptions, 'ssr' | 'astroAdapter' | 'router'>> {
  registerImportPlugin?: boolean;
  motion?: boolean;
  query?: boolean;
  uiGlob?: string;
  extraIgnores?: readonly string[];
  reactRefresh?: boolean;
  reactRouterRules?: boolean;
}

// ESLint reads no .gitignore. `.claude/**` is ignored whole, which already
// covers `.claude/worktrees`.
const toolingIgnores = [
  ...agentStateDirs.filter((dir) => !dir.startsWith('.claude/')),
  '.react-scan',
].map((dir) => `    '${dir}/**',`);
const testReportIgnores = testReportDirs.map((dir) => `    '${dir}/**',`);

// `@shadcn` sorts ahead of every other import, so it stays first under the
// generated config's own alphabetized import/order.
const shadcnLintImport = "import { plugin as shadcn } from '@shadcn/lint';";

// @shadcn/lint reads components.json on its own and only supports JS/TS
// sources. The shadcn-owned `ui` directory is already in globalIgnores.
const shadcnLintBlock = [
  '  {',
  "    files: ['**/*.{js,jsx,ts,tsx}'],",
  '    plugins: { shadcn },',
  "    settings: { shadcn: { note: 'See DESIGN.md for the design system rules.' } },",
  '    rules: {',
  "      'shadcn/no-restyle': ['error', { allow: ['layout'] }],",
  "      'shadcn/no-raw-colors': 'error',",
  "      'shadcn/no-arbitrary-values': ['error', { allow: ['layout'] }],",
  "      'shadcn/no-inline-styles': 'error',",
  "      'shadcn/require-static-classes': 'error',",
  "      'shadcn/no-unknown-classes': 'error',",
  '    },',
  '  },',
];

function featureLintFragments(options: EslintConfigOptions) {
  return featureLint(
    { motion: options.motion ?? false, query: options.query ?? false },
    options.framework,
  );
}

function renderFeatureLintImports(options: EslintConfigOptions) {
  return [...new Set(featureLintFragments(options).flatMap((fragment) => fragment.imports ?? []))];
}

function renderFeatureLint(options: EslintConfigOptions) {
  return featureLintFragments(options).flatMap(({ files, rules, configs }) => [
    ...(configs ?? []).map((config) => `  ${config},`),
    '  {',
    `    files: ['${files}'],`,
    '    rules: {',
    ...Object.entries(rules).map(([rule, value]) => `      '${rule}': '${value}',`),
    '    },',
    '  },',
  ]);
}

