async function updateHtmlTitle(
  projectRoot: string,
  projectName: string,
  executor: Executor,
) {
  const indexPath = path.join(projectRoot, 'index.html');
  if (!(await executor.pathExists(indexPath))) {
    throw new Error('Expected index.html to exist after creating the Vite app.');
  }

  const current = await executor.readFile(indexPath);
  if (!/<title>[\s\S]*?<\/title>/.test(current)) {
    throw new Error('Expected index.html generated by create-vite to contain a title.');
  }

  await executor.writeFile(
    indexPath,
    current.replace(
      /<title>[\s\S]*?<\/title>/,
      `<title>${humanizeProjectName(projectName)}</title>`,
    ),
  );
}

