  packageScriptConfig: FRAMEWORK_PACKAGE_SCRIPT_CONFIG.vite,
  playwrightServer: { hostFlag: '--host', port: 3000 },
  eslintConfigFile: 'eslint.config.js',
  prettierConfig: {
    tailwindStylesheet: 'src/index.css',
    extraPlugins: [],
  },
  vitestConfig: { kind: 'merge-vite' },
